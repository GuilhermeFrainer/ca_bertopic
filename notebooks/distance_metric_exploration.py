    # Section 6: Exploratory Distance Normalization Strategies
    # What happens when we normalize distance matrices before combining them?
    # Strategies:
    # 1. 95th-Percentile Normalization: D / P_95(D) (Used by MultiViewHDBSCAN)
    # 2. Median Normalization: D / median(D)
    # 3. Mean Normalization: D / mean(D)
