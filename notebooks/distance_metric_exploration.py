@app.cell
def _(X_meta, X_text, cdist, np, pdist, squareform):
    # Pairwise distance matrices computation
    # 1. Text View: Cosine Distance
    # np.clip guards against float precision quirks where cosine distance is slightly < 0
    _d_cos_vec = np.clip(pdist(X_text, metric="cosine"), 0.0, 2.0)
    D_text_cos = squareform(_d_cos_vec)
    np.fill_diagonal(D_text_cos, 0.0)

    # 2. Text View: Euclidean Distance
    _d_euc_vec = pdist(X_text, metric="euclidean")
    D_text_euc = squareform(_d_euc_vec)
    np.fill_diagonal(D_text_euc, 0.0)

    # 3. Metadata View: Euclidean Distance (standard Cartesian distance)
    _d_meta_euc_vec = pdist(X_meta, metric="euclidean")
    D_meta_euc = squareform(_d_meta_euc_vec)
    np.fill_diagonal(D_meta_euc, 0.0)

    # 4. Metadata View: Cosine Distance (to demonstrate directional distortion on tabular data)
    _d_meta_cos_vec = np.clip(pdist(X_meta, metric="cosine"), 0.0, 2.0)
    D_meta_cos = squareform(_d_meta_cos_vec)
    np.fill_diagonal(D_meta_cos, 0.0)

    # Helper function to extract strictly off-diagonal unique distances
    def get_off_diagonal_dists(D: np.ndarray) -> np.ndarray:
        _n_samples = D.shape[0]
        _i_idx, _j_idx = np.triu_indices(_n_samples, k=1)
        return D[_i_idx, _j_idx]

    off_text_cos = get_off_diagonal_dists(D_text_cos)
    off_text_euc = get_off_diagonal_dists(D_text_euc)
    off_meta_euc = get_off_diagonal_dists(D_meta_euc)
    off_meta_cos = get_off_diagonal_dists(D_meta_cos)

    return (
        D_meta_cos,
        D_meta_euc,
        D_text_cos,
        D_text_euc,
        get_off_diagonal_dists,
        off_meta_cos,
        off_meta_euc,
        off_text_cos,
        off_text_euc,
    )


@app.cell
def _(D_text_cos, D_text_euc, mo, np, plt, spearmanr):
    # Section 1: Monotonicity Sanity Check (Cosine vs Euclidean on L2-normalized Text)
    # Theory: For unit vectors u, v where ||u|| = ||v|| = 1:
    # ||u - v||^2 = ||u||^2 + ||v||^2 - 2(u . v) = 1 + 1 - 2 cos(u, v) = 2(1 - cos(u, v)) = 2 d_cos(u, v)
    # Therefore: d_euc = sqrt(2 * d_cos) and d_euc^2 = 2 * d_cos.

    _n_samples = D_text_cos.shape[0]
    _i_idx, _j_idx = np.triu_indices(_n_samples, k=1)

    _d_cos = D_text_cos[_i_idx, _j_idx]
    _d_euc = D_text_euc[_i_idx, _j_idx]
    _d_euc_sq = _d_euc**2
    _two_d_cos = 2.0 * _d_cos

    # Numerical difference
    _abs_diff = np.abs(_d_euc_sq - _two_d_cos)
    _max_diff = float(np.max(_abs_diff))
    _mean_diff = float(np.mean(_abs_diff))

    # Nearest-neighbor ranking equivalence check
    # Exclude self-distance by filling diagonal with infinity
    _D_cos_no_diag = D_text_cos.copy()
    _D_euc_no_diag = D_text_euc.copy()
    np.fill_diagonal(_D_cos_no_diag, np.inf)
    np.fill_diagonal(_D_euc_no_diag, np.inf)

    _nn_cos_1 = np.argmin(_D_cos_no_diag, axis=1)
    _nn_euc_1 = np.argmin(_D_euc_no_diag, axis=1)
    _fraction_top1_match = float(np.mean(_nn_cos_1 == _nn_euc_1))

    # Top-5 overlap check
    _top5_cos = np.argsort(_D_cos_no_diag, axis=1)[:, :5]
    _top5_euc = np.argsort(_D_euc_no_diag, axis=1)[:, :5]
    _top5_overlaps = [
        len(set(_top5_cos[row]).intersection(set(_top5_euc[row]))) / 5.0
        for row in range(_n_samples)
    ]
    _mean_top5_overlap = float(np.mean(_top5_overlaps))

    # Overall Spearman rank correlation
    _spearman_rho, _ = spearmanr(_d_cos, _d_euc)

    # Plot verification
    _fig, _axs = plt.subplots(1, 2, figsize=(11, 4.2))

    # Subplot A: d_euc^2 vs 2 * d_cos
    _axs[0].scatter(
        _two_d_cos[:2500],
        _d_euc_sq[:2500],
        alpha=0.35,
        s=10,
        color="#1f77b4",
        edgecolors="none",
    )
    _max_val = max(float(np.max(_two_d_cos)), float(np.max(_d_euc_sq)))
    _axs[0].plot(
        [0, _max_val],
        [0, _max_val],
        color="#d62728",
        linestyle="--",
        lw=1.5,
        label=r"Exact: $d_E^2 = 2 d_{\cos}$",
    )
    _axs[0].set_title(
        r"Monotonic Identity: $d_E^2$ vs $2 \cdot d_{\cos}$", fontweight="bold"
    )
    _axs[0].set_xlabel(r"$2 \cdot d_{\cos}(u, v)$")
    _axs[0].set_ylabel(r"$d_E(u, v)^2$")
    _axs[0].legend(loc="upper left")

    # Subplot B: Residual error distribution
    _axs[1].hist(_abs_diff, bins=40, color="#2ca02c", alpha=0.75, edgecolor="black")
    _axs[1].set_title("Floating-Point Precision Residuals", fontweight="bold")
    _axs[1].set_xlabel(r"Absolute Residual $|d_E^2 - 2 d_{\cos}|$")
    _axs[1].set_ylabel("Pairwise Count")
    _axs[1].ticklabel_format(style="sci", axis="x", scilimits=(0, 0))

    _fig.tight_layout()

    monotonicity_view = mo.vstack(
        [
            mo.md(
                r"""
            ## 1. Metric Choice Within a Normalized Representation: Cosine vs. Euclidean

            For any two unit-normalized vectors $u, v \in \mathbb{R}^d$ where $\|u\|_2 = \|v\|_2 = 1$:
            $$\|u - v\|_2^2 = \|u\|_2^2 + \|v\|_2^2 - 2(u \cdot v) = 1 + 1 - 2\cos(u, v) = 2(1 - \cos(u, v)) = 2 d_{\cos}(u, v)$$

            Therefore:
            $$d_E(u, v) = \sqrt{2 \cdot d_{\cos}(u, v)}$$

            Because $f(z) = \sqrt{2z}$ is strictly monotonically increasing for $z \ge 0$, **the nearest-neighbor rankings are identical**.
            """
            ),
            mo.hstack(
                [
                    mo.stat(
                        value=f"{_spearman_rho:.6f}",
                        label="Spearman Rank Correlation",
                        caption="Target: 1.000000",
                    ),
                    mo.stat(
                        value=f"{_fraction_top1_match * 100:.1f}%",
                        label="Identical 1-NN Match",
                        caption="Exact neighbor identity",
                    ),
                    mo.stat(
                        value=f"{_mean_top5_overlap * 100:.1f}%",
                        label="Top-5 Neighbor Overlap",
                        caption="Shared 5-nearest neighbors",
                    ),
                    mo.stat(
                        value=f"{_max_diff:.2e}",
                        label="Max Numerical Error",
                        caption="IEEE 754 precision limit",
                    ),
                ],
                justify="start",
                gap=2,
            ),
            mo.as_html(_fig),
            mo.md(
                """
            > **Methodological Takeaway**: Within a normalized semantic text representation, switching between Cosine and Euclidean
            > distance is a monotonic transformation of the exact same geometry. Nearest-neighbor graphs remain identical,
            > even though raw numerical distance values change.
            """
            ),
        ]
    )
    return (monotonicity_view,)


